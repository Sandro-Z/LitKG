# Shared helpers for scripts/baseline_pubtator3.sh and scripts/baseline_neo4j_builder.sh.
# Sourced, not executed. Expects ROOT, WORK, SYSTEM and a worker() function from the caller.
set -euo pipefail

SECRETS="$WORK/secrets"
VENV="$WORK/venv"
PIDFILE="$WORK/run.pid"
LOG="$WORK/logs/run.log"

log() { printf '%s %s\n' "$(date -u +%FT%TZ)" "$*"; }
die() { printf 'error: %s\n' "$*" >&2; exit 1; }
running() { [[ -f "$PIDFILE" ]] && kill -0 "$(cat "$PIDFILE")" 2>/dev/null; }

pick_python() {   # first interpreter >= 3.11 that can create a venv with pip
  local candidate
  for candidate in "${PYTHON:-}" python3 python3.13 python3.12 python3.11 python; do
    [[ -n "$candidate" ]] && command -v "$candidate" >/dev/null 2>&1 || continue
    "$candidate" -c 'import sys, ensurepip, venv; sys.exit(sys.version_info < (3, 11))' 2>/dev/null \
      && { command -v "$candidate"; return 0; }
  done
  return 1
}

setup_python() {
  # A venv without a working pip (e.g. "python3 -m venv" failed half-way) is rebuilt.
  if [[ -e "$VENV" ]] && ! "$VENV/bin/python" -c 'import sys, pip; sys.exit(sys.prefix == sys.base_prefix)' >/dev/null 2>&1; then
    log "removing incomplete virtualenv $VENV"
    rm -rf "$VENV" 2>/dev/null || die "cannot remove $VENV (probably created by an earlier sudo run); run: sudo rm -rf '$VENV'"
  fi
  if [[ ! -x "$VENV/bin/python" ]]; then
    local py
    py="$(pick_python)" || die "no Python >= 3.11 with venv/ensurepip found. Use your conda/pyenv Python, e.g.
  PYTHON=\$(which python) $0 ...   (do not prefix the script with sudo; it asks for sudo only for docker)
or install the venv package (Debian/Ubuntu: sudo apt install python3-venv)."
    log "creating virtualenv $VENV with $py"
    "$py" -m venv "$VENV" || { rm -rf "$VENV"; die "creating the virtualenv with $py failed"; }
  fi
  if [[ ! -f "$VENV/.deps-ok" || "$ROOT/baselines/requirements.txt" -nt "$VENV/.deps-ok" ]]; then
    log "installing pinned dependencies"
    "$VENV/bin/python" -m pip install --disable-pip-version-check -q -r "$ROOT/baselines/requirements.txt"
    touch "$VENV/.deps-ok"
  fi
}

fix_owner() {   # when started via sudo, hand the work directory back to the invoking user
  if [[ "${EUID:-$(id -u)}" == 0 && -n "${SUDO_UID:-}" ]]; then
    chown -R "$SUDO_UID:${SUDO_GID:-$SUDO_UID}" "$WORK" 2>/dev/null || true
  fi
}

store_key() {
  mkdir -p "$SECRETS"; chmod 700 "$SECRETS"
  if [[ ! -f "$SECRETS/llm_api_key" ]]; then
    local key="${LLM_API_KEY:-}"
    if [[ -z "$key" ]]; then
      [[ -t 0 ]] || die "set LLM_API_KEY (no terminal to prompt)"
      read -rsp "LLM API key (hidden; empty for a local model without auth): " key; echo
    fi
    (umask 077; printf '%s' "$key" > "$SECRETS/llm_api_key")
  fi
}

write_config() {   # $1 base_url  $2 model  $3 name  $4 extra toml (optional)
  mkdir -p "$WORK"/{corpus,cache,out,logs}
  (umask 077; cat > "$WORK/config.toml" <<EOF
# Generated by scripts/baseline_$SYSTEM.sh; contains no secrets.
[paths]
corpus = "$WORK/corpus/documents.json"
policy = "$WORK/corpus/policy.json"
id_map = "$WORK/corpus/id_map.csv"
pdfs = "$PDF_DIR"
cache = "$WORK/cache"
out = "$WORK/out"
corpus_name = "$3"

[llm]
base_url = "$1"
model = "$2"
litkg_model = "${LITKG_MODEL:-$2}"
api_key_file = "$SECRETS/llm_api_key"
concurrency = ${KGB_LLM_CONCURRENCY:-2}
${4:-}
EOF
)
}

kgb() { (cd "$WORK" && PYTHONPATH="$ROOT/baselines" "$VENV/bin/python" -m kgb.cli --config "$WORK/config.toml" "$@"); }

corpus_step() {   # rebuild only when the PDF set changes
  local fingerprint
  # PDF set + extractor code/deps: a fix in text extraction re-extracts the corpus on the next run.
  fingerprint="$( { (cd "$PDF_DIR" && find . -type f -iname '*.pdf' -printf '%p %s %T@\n' | sort); \
                    cat "$ROOT/baselines/kgb/corpus.py" "$ROOT/baselines/requirements.txt"; } | sha256sum | cut -d' ' -f1)"
  if [[ -s "$WORK/corpus/documents.json" && "$(cat "$WORK/corpus/.fingerprint" 2>/dev/null)" == "$fingerprint" ]]; then
    log "corpus up to date"; return 0
  fi
  log "extracting text from PDFs in $PDF_DIR"
  kgb corpus --pdfs "$PDF_DIR" --litkg-root "$ROOT" "$@"
  echo "$fingerprint" > "$WORK/corpus/.fingerprint"
}

finish_step() {
  if compgen -G "$WORK/out/graph.*.json" >/dev/null; then
    kgb validate "$WORK/out/graph.*.json" --qc-path "$ROOT" || log "validation reported errors"
    kgb stats >/dev/null
  fi
  log "DONE. Graphs:"; ls -1 "$WORK"/out/graph.*.json 2>/dev/null || log "no graph produced"
  fix_owner
}

parse_args() {
  PDF_DIR=""; BASE_URL=""; MODEL=""; NAME=""; DETACH=0; FORCE=0
  while [[ $# -gt 0 ]]; do
    case "$1" in
      --pdfs) PDF_DIR="$(cd "$2" && pwd)"; shift 2 ;;
      --llm-base-url) BASE_URL="$2"; shift 2 ;;
      --llm-model) MODEL="$2"; shift 2 ;;
      --name) NAME="$2"; shift 2 ;;
      --detach) DETACH=1; shift ;;
      --force) FORCE=1; shift ;;
      -h|--help) usage 0 ;;
      *) die "unknown option $1" ;;
    esac
  done
  [[ -n "$PDF_DIR" && -n "$BASE_URL" && -n "$MODEL" ]] || usage 1
  NAME="${NAME:-$(basename "$PDF_DIR")}"
  mkdir -p "$WORK"
  printf '%s\n' "$PDF_DIR" > "$WORK/pdf_dir"
}

follow() {   # show progress until the worker exits; Ctrl-C only stops watching
  echo "running in background (pid $(cat "$PIDFILE")); log: $LOG"
  echo "Ctrl-C stops watching only; the run continues. Check later: $0 status"
  tail -n 0 -F "$LOG" --pid="$(cat "$PIDFILE")" 2>/dev/null || true
  cmd_status
}

launch() {
  running && die "already running (pid $(cat "$PIDFILE")); see: $0 status"
  mkdir -p "$WORK/logs"
  setup_python
  store_key
  # Optional foreground step defined by a script (e.g. starting Docker services, which may ask for sudo).
  if declare -F before_background >/dev/null; then before_background; fi
  fix_owner
  nohup setsid "$0" _worker "$FORCE" >> "$LOG" 2>&1 < /dev/null &
  echo $! > "$PIDFILE"
  [[ "$DETACH" == 1 ]] && { echo "started (pid $!). Progress: $0 status   Log: $LOG"; return 0; }
  follow
}

cmd_status() {
  if running; then echo "status: running (pid $(cat "$PIDFILE"))"; else echo "status: not running"; fi
  [[ -s "$LOG" ]] && { echo "--- last log lines"; tail -n 6 "$LOG"; }
  ls -1 "$WORK"/out/graph.*.json 2>/dev/null | sed 's/^/graph: /' || true
}

cmd_stop() {
  if running; then kill -- -"$(cat "$PIDFILE")" 2>/dev/null || kill "$(cat "$PIDFILE")"; rm -f "$PIDFILE"; echo stopped
  else echo "not running"; fi
}

dispatch() {
  case "${1:-}" in
    status) cmd_status ;;
    logs) tail -n 200 -F "$LOG" ;;
    stop) cmd_stop ;;
    _worker) shift; trap 'rm -f "$PIDFILE"' EXIT; PDF_DIR="$(cat "$WORK/pdf_dir")"; worker "$@" ;;
    ""|-h|--help) usage 0 ;;
    *) parse_args "$@"; prepare_config; launch ;;
  esac
}
