#!/usr/bin/env bash
# Baseline graphs (PubTator3, Neo4j LLM Graph Builder) on the same corpus as a LitKG
# knowledge base, exported for QC import. One command, background, resumable.
#
#   scripts/run_baselines.sh start --qc-graph <QC graph id> --llm-base-url <url/v1> --llm-model <model>
#   scripts/run_baselines.sh status | logs | stop | down
#
# The LLM key is read from $LLM_API_KEY or prompted (hidden) once, and stored in
# data/baselines/secrets/llm_api_key (mode 600). It is never printed or written to logs.
# Running "start" again resumes: finished variants are skipped, PubTator/LLM responses and
# finished Neo4j documents are cached. Use --force to rebuild outputs from the caches.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
WORK="${KGB_WORK:-$ROOT/data/baselines}"
SECRETS="$WORK/secrets"
VENV="$WORK/venv"
BUILDER_DIR="$WORK/vendor/llm-graph-builder"
BUILDER_REPO="https://github.com/neo4j-labs/llm-graph-builder"
BUILDER_REF="v0.8.7"
BUILDER_COMMIT="1ade47de63edb161e5ea37a277141643f3af3142"
COMPOSE_FILE="$ROOT/baselines/deploy/docker-compose.builder.yml"
PIDFILE="$WORK/run.pid"
LOG="$WORK/logs/run.log"
STATUS="$WORK/logs/status.txt"
DEFAULT_VARIANTS="pubtator3-native pubtator3-llm neo4j-builder-sametext"
export KGB_SECRETS="$SECRETS" KGB_BUILDER_DIR="$BUILDER_DIR"
export KGB_NEO4J_BOLT_PORT="${KGB_NEO4J_BOLT_PORT:-17687}" KGB_BUILDER_PORT="${KGB_BUILDER_PORT:-18000}"

log() { printf '%s %s\n' "$(date -u +%FT%TZ)" "$*"; }
die() { printf 'error: %s\n' "$*" >&2; exit 1; }
compose() { docker compose -f "$COMPOSE_FILE" "$@"; }
running() { [[ -f "$PIDFILE" ]] && kill -0 "$(cat "$PIDFILE")" 2>/dev/null; }

usage() { sed -n '2,11p' "$0" | sed 's/^# \{0,1\}//'; exit "${1:-0}"; }

# ------------------------------------------------------------------ setup steps

setup_python() {
  local py="${PYTHON:-python3}"
  "$py" -c 'import sys; sys.exit(sys.version_info < (3, 11))' || die "Python >= 3.11 required ($py)"
  if [[ ! -x "$VENV/bin/python" ]]; then
    log "creating virtualenv $VENV"
    "$py" -m venv "$VENV"
  fi
  if [[ ! -f "$VENV/.deps-ok" || "$ROOT/baselines/requirements.txt" -nt "$VENV/.deps-ok" ]]; then
    log "installing baseline dependencies"
    "$VENV/bin/pip" install --disable-pip-version-check -q -r "$ROOT/baselines/requirements.txt"
    touch "$VENV/.deps-ok"
  fi
}

neo4j_ready() {
  "$VENV/bin/python" - "$KGB_NEO4J_BOLT_PORT" "$SECRETS/neo4j_password" 2>/dev/null <<'PY'
import sys
from neo4j import GraphDatabase
with GraphDatabase.driver(f"bolt://127.0.0.1:{sys.argv[1]}", auth=("neo4j", open(sys.argv[2]).read().strip())) as d:
    d.verify_connectivity()
PY
}

setup_builder() {
  if ! command -v docker >/dev/null || ! docker compose version >/dev/null 2>&1; then
    log "docker compose is required for the Neo4j LLM Graph Builder variants"; return 1
  fi
  if [[ ! -d "$BUILDER_DIR/.git" ]]; then
    log "cloning $BUILDER_REPO@$BUILDER_REF"
    git clone -q --depth 1 --branch "$BUILDER_REF" "$BUILDER_REPO" "$BUILDER_DIR" || return 1
  fi
  local head; head="$(git -C "$BUILDER_DIR" rev-parse HEAD)"
  if [[ "$head" != "$BUILDER_COMMIT" ]]; then
    log "builder checkout is $head, expected pinned $BUILDER_COMMIT"; return 1
  fi
  log "building/starting Neo4j + builder backend (first build downloads several GB)"
  compose up -d --build || return 1
  local i
  for i in $(seq 1 120); do
    if neo4j_ready && curl -sf -o /dev/null "http://127.0.0.1:$KGB_BUILDER_PORT/docs"; then
      log "Neo4j and builder backend are ready"; return 0
    fi
    sleep 10
  done
  log "Neo4j/builder backend not ready after 20 minutes; see: docker compose -f $COMPOSE_FILE logs"
  return 1
}

write_config() {
  local qc_graph="$1" qc_url="$2" base_url="$3" model="$4" litkg_model="$5" name="$6"
  mkdir -p "$SECRETS" "$WORK"/{corpus,cache,out,logs}
  chmod 700 "$SECRETS"
  umask 077
  if [[ ! -s "$SECRETS/llm_api_key" ]]; then
    local key="${LLM_API_KEY:-}"
    if [[ -z "$key" ]]; then
      [[ -t 0 ]] || die "set LLM_API_KEY (no terminal to prompt)"
      read -rsp "LLM API key (hidden; empty for a local model without auth): " key; echo
    fi
    printf '%s' "$key" > "$SECRETS/llm_api_key"
  fi
  [[ -s "$SECRETS/neo4j_password" ]] || "$VENV/bin/python" -c 'import secrets;print(secrets.token_hex(16),end="")' > "$SECRETS/neo4j_password"
  printf 'NEO4J_AUTH=neo4j/%s\n' "$(cat "$SECRETS/neo4j_password")" > "$SECRETS/neo4j.env"
  # The builder runs in a container: a localhost LLM endpoint is reached via host.docker.internal.
  local builder_url="${base_url/:\/\/localhost/://host.docker.internal}"
  builder_url="${builder_url/:\/\/127.0.0.1/://host.docker.internal}"
  printf 'LLM_MODEL_CONFIG_LITKG_COMPAT=%s,%s,%s\nNEO4J_USERNAME=neo4j\nNEO4J_PASSWORD=%s\n' \
    "$model" "$builder_url" "$(cat "$SECRETS/llm_api_key")" "$(cat "$SECRETS/neo4j_password")" > "$SECRETS/builder-backend.env"
  cat > "$WORK/config.toml" <<EOF
# Generated by scripts/run_baselines.sh; contains no secrets.
[paths]
corpus = "$WORK/corpus/documents.json"
policy = "$WORK/corpus/policy.json"
id_map = "$WORK/corpus/id_map.csv"
pdfs = "$ROOT/data/uploads"
cache = "$WORK/cache"
out = "$WORK/out"
corpus_name = "$name"

[llm]
base_url = "$base_url"
model = "$model"
litkg_model = "$litkg_model"
api_key_file = "$SECRETS/llm_api_key"
concurrency = ${KGB_LLM_CONCURRENCY:-2}

[neo4j]
uri = "bolt://127.0.0.1:$KGB_NEO4J_BOLT_PORT"
backend_uri = "bolt://neo4j:7687"
backend_url = "http://127.0.0.1:$KGB_BUILDER_PORT"
password_file = "$SECRETS/neo4j_password"
model = "litkg_compat"
model_name = "$model"
builder_ref = "$BUILDER_REF"
builder_commit = "$BUILDER_COMMIT"
dedicated_database = true
EOF
  printf '%s\n%s\n' "$qc_graph" "$qc_url" > "$WORK/corpus/source.txt"
}

fetch_corpus() {
  local qc_graph qc_url
  { read -r qc_graph; read -r qc_url; } < "$WORK/corpus/source.txt"
  if [[ -s "$WORK/corpus/documents.json" && -s "$WORK/corpus/policy.json" ]]; then
    log "corpus already present (QC graph $qc_graph)"; return 0
  fi
  log "downloading documents/policy of QC graph $qc_graph from $qc_url"
  curl -sf "$qc_url/api/graphs/$qc_graph" | "$VENV/bin/python" -c '
import json, sys
g = json.load(sys.stdin)["graph"]
out = sys.argv[1]
json.dump(g["documents"], open(out + "/documents.json", "w"), ensure_ascii=False)
json.dump(g["policy"], open(out + "/policy.json", "w"), ensure_ascii=False)
print(len(g["documents"]), "documents")' "$WORK/corpus"
}

kgb() { (cd "$WORK" && PYTHONPATH="$ROOT/baselines" "$VENV/bin/python" -m kgb.cli --config "$WORK/config.toml" "$@"); }

# ------------------------------------------------------------------ worker

worker() {
  local variants="$1" force="$2"
  trap 'log "worker stopped"; rm -f "$PIDFILE"' EXIT
  log "worker started (variants: $variants)"
  fetch_corpus
  kgb prep
  local v system variant out
  for v in $variants; do
    case "$v" in
      pubtator3-native|pubtator3-llm) system=pubtator3; variant="${v#pubtator3-}" ;;
      neo4j-builder-sametext|neo4j-builder-pdfnative|neo4j-builder-no-schema) system=neo4j; variant="${v#neo4j-builder-}" ;;
      *) log "unknown variant $v"; echo "$v unknown" >> "$STATUS"; continue ;;
    esac
    out="$WORK/out/graph.$v.json"
    if [[ -s "$out" && "$force" != 1 ]]; then
      log "$v: output exists, skipped (use --force to rebuild from caches)"; echo "$v done (existing)" >> "$STATUS"; continue
    fi
    if [[ "$system" == neo4j ]] && ! setup_builder; then
      log "$v: builder unavailable"; echo "$v failed (builder unavailable)" >> "$STATUS"; continue
    fi
    log "$v: running"; echo "$v running" >> "$STATUS"
    if kgb run "$system" --variant "$variant" --pmid-from-external-id; then
      log "$v: finished"; echo "$v done" >> "$STATUS"
    else
      log "$v: FAILED (rerun start to resume from caches)"; echo "$v failed" >> "$STATUS"
    fi
  done
  if compgen -G "$WORK/out/graph.*.json" >/dev/null; then
    kgb validate "$WORK/out/graph.*.json" --qc-path "$ROOT" || log "validation reported errors"
    kgb stats
  fi
  log "all variants processed; outputs in $WORK/out"
}

# ------------------------------------------------------------------ commands

cmd_start() {
  local qc_graph="" qc_url="${QC_URL:-http://127.0.0.1:8090}" base_url="" model="" litkg_model="" name=""
  local variants="$DEFAULT_VARIANTS" force=0
  while [[ $# -gt 0 ]]; do
    case "$1" in
      --qc-graph) qc_graph="$2"; shift 2 ;;
      --qc-url) qc_url="$2"; shift 2 ;;
      --llm-base-url) base_url="$2"; shift 2 ;;
      --llm-model) model="$2"; shift 2 ;;
      --litkg-model) litkg_model="$2"; shift 2 ;;
      --name) name="$2"; shift 2 ;;
      --variants) variants="$2"; shift 2 ;;
      --force) force=1; shift ;;
      -h|--help) usage ;;
      *) die "unknown option $1" ;;
    esac
  done
  running && die "already running (pid $(cat "$PIDFILE")); see: $0 status"
  mkdir -p "$WORK/logs"
  setup_python
  if [[ -n "$qc_graph$base_url$model" ]]; then
    [[ -n "$qc_graph" && -n "$base_url" && -n "$model" ]] || die "--qc-graph, --llm-base-url and --llm-model go together"
    if [[ -f "$WORK/corpus/source.txt" && "$(head -1 "$WORK/corpus/source.txt")" != "$qc_graph" ]]; then
      die "data/baselines was prepared for QC graph $(head -1 "$WORK/corpus/source.txt"); move it away or set KGB_WORK"
    fi
    write_config "$qc_graph" "$qc_url" "$base_url" "$model" "${litkg_model:-$model}" "${name:-qc-graph-$qc_graph}"
  fi
  [[ -f "$WORK/config.toml" ]] || die "first run needs --qc-graph, --llm-base-url and --llm-model"
  : > "$STATUS"
  nohup setsid "$0" _worker "$variants" "$force" >> "$LOG" 2>&1 < /dev/null &
  echo $! > "$PIDFILE"
  echo "started in background (pid $!). Progress: $0 status   Log: $LOG"
}

cmd_status() {
  if running; then echo "running (pid $(cat "$PIDFILE"))"; else echo "not running"; fi
  [[ -s "$STATUS" ]] && { echo "--- variants"; cat "$STATUS"; }
  [[ -s "$LOG" ]] && { echo "--- last log lines"; tail -n 8 "$LOG"; }
  ls -1 "$WORK"/out/graph.*.json 2>/dev/null | sed 's/^/output: /' || true
}

cmd_stop() {
  if running; then kill -- -"$(cat "$PIDFILE")" 2>/dev/null || kill "$(cat "$PIDFILE")"; rm -f "$PIDFILE"; echo stopped
  else echo "not running"; fi
}

case "${1:-}" in
  start) shift; cmd_start "$@" ;;
  status) cmd_status ;;
  logs) tail -n "${2:-100}" -f "$LOG" ;;
  stop) cmd_stop ;;
  down) compose down ;;
  _worker) shift; worker "$@" ;;
  -h|--help|"") usage ;;
  *) usage 1 ;;
esac
